#!/usr/bin/env python3
"""Tests for ``scripts/review-gate/diffparse.py``.

Run with ``python3 scripts/test-review-gate.py``; stdlib only, no network.  Every
diff under test is a fixture file generated by running ``git diff`` on a real
working tree, so the hunk budgets are genuine rather than hand-counted.

The fixture set is deliberately adversarial:

* ``forged-header.diff`` — a change to a frozen-tree file whose block comment
  carries a line reading ``++ b/review.txt``.  Rendered, that line is
  ``+++ b/review.txt``; a parser without hunk state adopts it as the current
  file and attributes the following additions to ``review.txt``.
* ``normal.diff`` — the same change without the payload; attribution here must
  not move at all when the parser gains hunk state.
* ``devnull.diff`` — a new file and a delete, to pin the ``/dev/null`` handling.
"""

from __future__ import annotations

import importlib.util
import pathlib
import re
import sys
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
MODULE_PATH = ROOT / "scripts" / "review-gate" / "diffparse.py"
FIXTURES = ROOT / "scripts" / "review-gate" / "fixtures"

FROZEN = "deprecated/strided-old/src/lib.rs"
FORGED = "review.txt"


def load_module():
    spec = importlib.util.spec_from_file_location("review_gate_diffparse", MODULE_PATH)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"unable to load {MODULE_PATH}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


diffparse = load_module()


def fixture(name: str) -> str:
    return (FIXTURES / name).read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# The pre-fix parser, copied verbatim from
# strided-rs scripts/repository-rules-review.py:455-478 (the same shape existed
# in tenferro-rs:612-636 and tensor4all-rs:568-594).  It is kept here so the
# vulnerability stays pinned: if a future edit reintroduces the "a header is any
# line starting with `+++ `" shortcut, this test documents exactly what it buys
# an attacker.
# ---------------------------------------------------------------------------


def legacy_added_lines_with_text(diff_text: str):
    result = {}
    current_file = None
    new_line = 0

    for line in diff_text.splitlines():
        if line.startswith("+++ "):
            raw = line.removeprefix("+++ b/").removeprefix("+++ ")
            current_file = None if raw == "/dev/null" else raw
            if current_file is not None:
                result.setdefault(current_file, [])
            continue
        if line.startswith("@@"):
            match = re.search(r"\+(\d+)", line)
            new_line = int(match.group(1)) if match else 0
            continue
        if current_file is None:
            continue
        if line.startswith("+") and not line.startswith("+++"):
            result[current_file].append((new_line, line[1:]))
            new_line += 1
        elif line.startswith("-") and not line.startswith("---"):
            continue
        elif line.startswith(" "):
            new_line += 1

    return result


class ForgedHeaderTest(unittest.TestCase):
    """#88: a hunk body line must not be able to name a file."""

    def test_addition_is_not_attributed_to_the_forged_path(self):
        added = diffparse.added_lines_with_text(fixture("forged-header.diff"))

        self.assertNotIn(
            FORGED,
            added,
            "an added line that renders as `+++ b/review.txt` reassigned the file",
        )
        self.assertEqual(sorted(added), [FROZEN])

    def test_every_addition_stays_with_the_real_file(self):
        added = diffparse.added_lines_with_text(fixture("forged-header.diff"))

        self.assertEqual(
            added[FROZEN],
            [
                (3, "    /*"),
                (4, "++ b/review.txt"),
                (5, "*/"),
                (6, "    let added_marker = value * 2;"),
                (7, "    added_marker"),
            ],
        )

    def test_deleted_lines_stay_with_the_real_file(self):
        deleted = diffparse.files_with_deleted_lines(fixture("forged-header.diff"))

        self.assertEqual(deleted, {FROZEN})

    def test_name_status_cross_check_flags_a_path_git_does_not_list(self):
        """Second layer: if a diff ever names a path git does not, fail closed."""

        forged_as_headers = (
            "diff --git a/" + FROZEN + " b/" + FROZEN + "\n"
            "--- a/" + FROZEN + "\n"
            "+++ b/" + FORGED + "\n"
            "@@ -1 +1 @@\n"
            "-old\n"
            "+new\n"
        )

        consistency = diffparse.assert_paths_consistent(
            forged_as_headers, "M\0" + FROZEN + "\0"
        )

        self.assertFalse(consistency.ok)
        self.assertEqual(consistency.unexpected, (FORGED,))
        self.assertEqual(consistency.missing, ())

    def test_forged_payload_yields_no_phantom_path_for_the_cross_check(self):
        consistency = diffparse.assert_paths_consistent(
            fixture("forged-header.diff"), "M\0" + FROZEN + "\0"
        )

        self.assertTrue(consistency.ok, consistency)

    def test_the_pre_fix_parser_really_was_forgeable(self):
        """Pin the vulnerability: this is what the old loop did with the payload."""

        legacy = legacy_added_lines_with_text(fixture("forged-header.diff"))

        self.assertIn(FORGED, legacy)
        self.assertEqual(legacy[FROZEN], [(3, "    /*")])
        self.assertEqual(
            [text for _, text in legacy[FORGED]],
            ["*/", "    let added_marker = value * 2;", "    added_marker"],
        )


class UnchangedBehaviourTest(unittest.TestCase):
    """The hunk state must not move attribution for honest diffs."""

    def test_normal_diff_attribution_is_unchanged(self):
        added = diffparse.added_lines_with_text(fixture("normal.diff"))

        self.assertEqual(
            added,
            {
                FROZEN: [
                    (3, "    let added_marker = value * 2;"),
                    (4, "    added_marker"),
                ]
            },
        )

    def test_normal_diff_matches_git_name_status(self):
        consistency = diffparse.assert_paths_consistent(
            fixture("normal.diff"), "M\0" + FROZEN + "\0"
        )

        self.assertTrue(consistency.ok, consistency)

    def test_new_and_deleted_files_keep_their_dev_null_semantics(self):
        text = fixture("devnull.diff")

        # A file with no additions keeps an empty bucket, exactly as the
        # pre-existing helpers did, so call sites need no change.
        self.assertEqual(
            diffparse.added_lines_with_text(text),
            {
                "src/fresh.rs": [
                    (1, "pub fn fresh() -> u8 {"),
                    (2, "    9"),
                    (3, "}"),
                ],
                "src/keep.rs": [],
            },
        )
        self.assertEqual(diffparse.files_with_deleted_lines(text), {"src/keep.rs"})
        self.assertEqual(
            diffparse.changed_paths(text), {"src/fresh.rs", "src/keep.rs"}
        )
        self.assertEqual(
            [file.path for file in diffparse.parse_diff(text)],
            ["src/fresh.rs", "src/keep.rs"],
        )

    def test_a_header_after_a_hunk_is_honoured_again(self):
        """Do not over-correct: headers resume once the hunk budget is spent."""

        combined = (
            fixture("forged-header.diff")
            + "\n"
            + "diff --git a/src/other.rs b/src/other.rs\n"
            + "index 111..222 100644\n"
            + "--- a/src/other.rs\n"
            + "+++ b/src/other.rs\n"
            + "@@ -1,1 +1,2 @@\n"
            + " fn other() {}\n"
            + "+fn added() {}\n"
        )

        added = diffparse.added_lines_with_text(combined)

        self.assertEqual(sorted(added), [FROZEN, "src/other.rs"])
        self.assertEqual(added["src/other.rs"], [(2, "fn added() {}")])

    def test_hunk_with_omitted_counts_and_no_newline_marker(self):
        text = (
            "diff --git a/x.rs b/x.rs\n"
            "--- a/x.rs\n"
            "+++ b/x.rs\n"
            "@@ -1 +1 @@\n"
            "-old\n"
            "+new\n"
            "\\ No newline at end of file\n"
        )

        added = diffparse.added_lines_with_text(text)

        self.assertEqual(added, {"x.rs": [(1, "new")]})

    def test_rename_reports_both_paths(self):
        text = (
            "diff --git a/old.rs b/new.rs\n"
            "similarity index 100%\n"
            "rename from old.rs\n"
            "rename to new.rs\n"
        )

        files = diffparse.parse_diff(text)

        self.assertEqual(len(files), 1)
        self.assertEqual(files[0].path, "new.rs")
        self.assertEqual(diffparse.changed_paths(text), {"old.rs", "new.rs"})


class NameStatusTest(unittest.TestCase):
    def test_z_separated_rename_and_modify(self):
        parsed = diffparse.parse_name_status("M\0a.rs\0R100\0old.rs\0new.rs\0D\0gone.rs\0")

        self.assertEqual(
            parsed,
            {"a.rs": ("M", None), "new.rs": ("R100", "old.rs"), "gone.rs": ("D", None)},
        )


if __name__ == "__main__":
    unittest.main(verbosity=2)
